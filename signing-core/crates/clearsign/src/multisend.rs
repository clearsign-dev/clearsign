/// Why an address is not decoded as a batch.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NotABatch {
    /// The address is not a published MultiSend deployment at all.
    UnknownAddress,
    /// The address is a published deployment, but not on this chain. Either the
    /// chain ID is one Safe does not list it for, or there is no chain ID to
    /// check (a pre-EIP-155 legacy transaction).
    WrongChain(&'static Deployment),
}

/// The deployment at `addr` on chain `chain_id`, if the decoder will look inside
/// it. A published address on an unpublished chain is not trusted: nothing in
/// the signed bytes says what code lives there.
pub fn lookup(addr: &Address, chain_id: Option<u64>) -> Result<&'static Deployment, NotABatch> {
    let found = DEPLOYMENTS
        .iter()
        .find(|d| d.address == *addr)
        .ok_or(NotABatch::UnknownAddress)?;
    match chain_id {
        Some(id) if found.chains.binary_search(&id).is_ok() => Ok(found),
        _ => Err(NotABatch::WrongChain(found)),
    }
}

/// One call inside a batch.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BatchCall<'a> {
    pub operation: Operation,
    pub to: Address,
    pub value: U256,
    pub data: &'a [u8],
}

/// Decode the packed `transactions` argument of `multiSend`.
///
/// Each element is `operation(uint8) | to(address) | value(uint256) |
/// dataLength(uint256) | data`, concatenated with no padding. Anything that does
/// not consume the argument exactly is an error, never a partial result: a batch
/// the decoder half-understands is the case this whole project exists to refuse.
pub fn decode_batch(packed: &[u8]) -> Result<Vec<BatchCall<'_>>, Error> {
    let mut calls = Vec::new();
    let mut pos = 0usize;
    while pos < packed.len() {
        if calls.len() >= MAX_BATCH_CALLS_PARSED {
            return Err(Error::TooDeep);
        }
        let header_end = pos.checked_add(HEADER).ok_or(Error::IntegerOverflow)?;
        let header = packed.get(pos..header_end).ok_or(Error::Truncated)?;
        let operation = Operation::from_u8(*header.first().ok_or(Error::Truncated)?);
        let to: Address = header
            .get(1..21)
            .ok_or(Error::Truncated)?
            .try_into()
            .map_err(|_| Error::InvalidAddress)?;
        let value = U256::from_be_slice(header.get(21..53).ok_or(Error::Truncated)?)?;
        let len = U256::from_be_slice(header.get(53..85).ok_or(Error::Truncated)?)?
            .to_u64()
            .and_then(|v| usize::try_from(v).ok())
            .ok_or(Error::IntegerOverflow)?;
        let end = header_end.checked_add(len).ok_or(Error::IntegerOverflow)?;
        let data = packed.get(header_end..end).ok_or(Error::Truncated)?;
        calls.push(BatchCall {
            operation,
            to,
            value,
            data,
        });
        pos = end;
    }
    if calls.is_empty() {
        return Err(Error::Truncated);
    }
    Ok(calls)
}

