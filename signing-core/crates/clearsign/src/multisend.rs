//! Safe MultiSend batches.
//!
//! A batch is normally executed with DELEGATECALL, which the decoder otherwise
//! refuses to interpret (INV-2, and the Bybit pattern). The one exception is a
//! delegatecall into a *pinned* MultiSend deployment, whose only behaviour is to
//! replay the calls packed into its argument.
//!
//! Without this, every Safe batch is CRITICAL. A warning that always fires is a
//! warning nobody reads, which is blind signing wearing a hat.
//!
//! **The trust assumption, stated plainly.** The signer sees only the bytes to
//! be signed. It cannot read chain state, so it cannot confirm that the pinned
//! address holds the audited MultiSend code on the chain this transaction
//! targets. The addresses below are Safe's own published deployments, taken from
//! `safe-global/safe-deployments` on 17 Sep 2026; every other address stays
//! CRITICAL and undecoded.

use alloc::string::String;
use alloc::vec::Vec;

use crate::address::Address;
use crate::calls::Operation;
use crate::{Error, U256};

/// A published MultiSend deployment the decoder will look inside.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Deployment {
    pub address: Address,
    /// The same address as published, EIP-55 checksummed. Tests require that it
    /// matches `address`, so a transcription error cannot reach a release.
    pub checksummed: &'static str,
    /// `MultiSend` or `MultiSendCallOnly`.
    pub contract: &'static str,
    pub version: &'static str,
    /// Safe's own name for the deployment variant: canonical, eip155 or zksync.
    pub variant: &'static str,
    /// The chain IDs Safe publishes this deployment on, ascending. An address is
    /// only meaningful together with a chain: the same 20 bytes hold different
    /// code on a chain where this deployment was never made.
    pub chains: &'static [u64],
}

/// `multiSend(bytes)`. Checked against keccak256 of the signature in tests.
pub const SEL_MULTI_SEND: [u8; 4] = [0x8d, 0x80, 0xff, 0x0a];

/// How many calls in one batch the decoder will display. A larger batch is not
/// summarised, because a person cannot review what they cannot see.
pub const MAX_BATCH_CALLS: usize = 32;

/// How many calls the decoder will *parse* to judge risk, as opposed to display.
///
/// Reading past the display limit costs little and answers the question that
/// matters about an over-long batch: is there a DELEGATECALL in the part you are
/// not being shown? Without this the person acknowledges "batch too long" and
/// signs whatever is in it.
pub const MAX_BATCH_CALLS_PARSED: usize = 1024;

/// Packed header per call: operation(1) + to(20) + value(32) + dataLength(32).
